function node(name, className, properties = {}) {
  return { name, className, guid: id(), pins: [], ...properties };
}

function pin(owner, name, pinType, options = {}) {
  const result = {
    owner,
    id: id(),
    name,
    type: pinType,
    direction: options.direction || "input",
    defaultValue: options.defaultValue,
    autogeneratedDefaultValue: options.autogeneratedDefaultValue,
    defaultObject: options.defaultObject,
    hidden: options.hidden || false,
    const: options.const || false,
    advanced: options.advanced || false,
    links: [],
  };
  owner.pins.push(result);
  return result;
}

function link(a, b) {
  a.links.push(b);
  b.links.push(a);
}

function quote(value) {
  return `"${String(value).replaceAll("\\", "\\\\").replaceAll('"', '\\"')}"`;
}

function renderPin(p) {
  const fields = [
    `PinId=${p.id}`,
    `PinName=${quote(p.name)}`,
    ...(p.direction === "output" ? ['Direction="EGPD_Output"'] : []),
    `PinType.PinCategory=${quote(p.type.category)}`,
    `PinType.PinSubCategory=${quote(p.type.subCategory)}`,
    `PinType.PinSubCategoryObject=${p.type.object ? quote(p.type.object) : "None"}`,
    "PinType.PinSubCategoryMemberReference=()",
    "PinType.PinValueType=()",
    `PinType.ContainerType=${p.type.container}`,
    "PinType.bIsReference=False",
    `PinType.bIsConst=${p.const ? "True" : "False"}`,
    "PinType.bIsWeakPointer=False",
    "PinType.bIsUObjectWrapper=False",
    "PinType.bSerializeAsSinglePrecisionFloat=False",
    ...(p.defaultValue !== undefined ? [`DefaultValue=${quote(p.defaultValue)}`] : []),
    ...(p.autogeneratedDefaultValue !== undefined
      ? [`AutogeneratedDefaultValue=${quote(p.autogeneratedDefaultValue)}`]
      : []),
    ...(p.defaultObject ? [`DefaultObject=${quote(p.defaultObject)}`] : []),
    ...(p.links.length
      ? [
          `LinkedTo=(${p.links
            .map(target => `${target.owner.name} ${target.id},`)
            .join("")})`,
        ]
      : []),
    "PersistentGuid=00000000000000000000000000000000",
    `bHidden=${p.hidden ? "True" : "False"}`,
    "bNotConnectable=False",
    "bDefaultValueIsReadOnly=False",
    "bDefaultValueIsIgnored=False",
    `bAdvancedView=${p.advanced ? "True" : "False"}`,
    "bOrphanedPin=False",
  ];
  return `   CustomProperties Pin (${fields.join(",")},)`;
}

function renderNode(n) {
  const lines = [
    `Begin Object Class=/Script/BlueprintGraph.${n.className} Name=${quote(n.name)}`,
  ];
  if (n.functionReference) lines.push(`   FunctionReference=${n.functionReference}`);
  if (n.variableReference) lines.push(`   VariableReference=${n.variableReference}`);
  if (n.selfContextInfo) lines.push(`   SelfContextInfo=${n.selfContextInfo}`);
  if (n.targetType) lines.push(`   TargetType=${quote(n.targetType)}`);
  if (n.defaultsToPure) lines.push("   bDefaultsToPureFunc=True");
  lines.push(`   NodePosX=${n.x || 0}`, `   NodePosY=${n.y || 0}`, `   NodeGuid=${n.guid}`);
  lines.push(...n.pins.map(renderPin), "End Object");
  return lines.join("\r\n");
}

function write(name, nodes) {
  fs.writeFileSync(
    path.join(__dirname, name),
    `${nodes.map(renderNode).join("\r\n")}\r\n`,
  );
}

