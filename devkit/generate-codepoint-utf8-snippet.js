function renderPin(pin) {
  const parts = [
    `PinId=${pin.id}`,
    `PinName="${pin.name}"`,
    ...(pin.direction === "output" ? ['Direction="EGPD_Output"'] : []),
    `PinType.PinCategory="${pin.category}"`,
    `PinType.PinSubCategory="${pin.subCategory}"`,
    `PinType.PinSubCategoryObject=${pin.subCategoryObject}`,
    "PinType.PinSubCategoryMemberReference=()",
    "PinType.PinValueType=()",
    `PinType.ContainerType=${pin.container}`,
    `PinType.bIsReference=${pin.isReference ? "True" : "False"}`,
    `PinType.bIsConst=${pin.isConst ? "True" : "False"}`,
    "PinType.bIsWeakPointer=False",
    "PinType.bIsUObjectWrapper=False",
    "PinType.bSerializeAsSinglePrecisionFloat=False",
    ...(pin.defaultValue !== undefined ? [`DefaultValue="${pin.defaultValue}"`] : []),
    ...(pin.autogeneratedDefaultValue !== undefined
      ? [`AutogeneratedDefaultValue="${pin.autogeneratedDefaultValue}"`]
      : []),
    ...(pin.defaultObject !== undefined ? [`DefaultObject=${pin.defaultObject}`] : []),
    ...(pin.links.length
      ? [`LinkedTo=(${pin.links.map(link => `${link.node.name} ${link.id},`).join("")})`]
      : []),
    "PersistentGuid=00000000000000000000000000000000",
    `bHidden=${pin.hidden ? "True" : "False"}`,
    "bNotConnectable=False",
    "bDefaultValueIsReadOnly=False",
    `bDefaultValueIsIgnored=${pin.defaultValueIgnored ? "True" : "False"}`,
    "bAdvancedView=False",
    "bOrphanedPin=False"
  ];
  return `   CustomProperties Pin (${parts.join(",")},)`;
}

function renderNode(node) {
  return [
    `Begin Object Class=${node.className} Name="${node.name}"`,
    ...node.properties.map(property => `   ${property}`),
    `   NodePosX=${node.x}`,
    `   NodePosY=${node.y}`,
    `   NodeGuid=${node.guid}`,
    ...node.pins.map(renderPin),
    ...node.userDefinedPins.map(pin => `   ${pin}`),
    "End Object"
  ].join("\n");
}

