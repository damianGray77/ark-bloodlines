function calculation(prefix, x, y, sourcePin, divisor, remainderDivisor, addend) {
  let currentPin = sourcePin;
  let nextX = x;

  if (divisor !== 1) {
    const divide = pureMathNode(`K2Node_CallFunction_ABLUTF8_${prefix}_Divide`, "Divide_IntInt", nextX, y);
    divide.b.defaultValue = String(divisor);
    connect(currentPin, divide.a);
    currentPin = divide.result;
    nextX += 210;
  }

  if (remainderDivisor) {
    const remainder = pureMathNode(`K2Node_CallFunction_ABLUTF8_${prefix}_Remainder`, "Percent_IntInt", nextX, y);
    remainder.b.defaultValue = String(remainderDivisor);
    connect(currentPin, remainder.a);
    currentPin = remainder.result;
    nextX += 210;
  }

  const add = pureMathNode(`K2Node_CallFunction_ABLUTF8_${prefix}_Add`, "Add_IntInt", nextX, y);
  add.b.defaultValue = String(addend);
  connect(currentPin, add.a);
  return add.result;
}

