function pureLibraryNode(name, owner, functionName, x, y, inputs, output) {
  const node = addNode(
    "/Script/BlueprintGraph.K2Node_CallFunction",
    name,
    x,
    y,
    [
      "bDefaultsToPureFunc=True",
      `FunctionReference=(MemberParent="/Script/CoreUObject.Class'/Script/Engine.${owner}'",MemberName="${functionName}")`
    ]
  );
  addPin(node, "self", "object", {
    hidden: true,
    subCategoryObject: `"/Script/CoreUObject.Class'/Script/Engine.${owner}'"`,
    defaultObject: `"/Script/Engine.Default__${owner}"`
  });
  const inputPins = Object.fromEntries(
    inputs.map(input => [
      input.name,
      addPin(node, input.name, input.category, {
        container: input.container || "None",
        defaultValue: input.defaultValue,
        autogeneratedDefaultValue: input.autogeneratedDefaultValue
      })
    ])
  );
  const result = addPin(node, output.name || "ReturnValue", output.category, {
    direction: "output",
    container: output.container || "None",
    defaultValue: output.defaultValue,
    autogeneratedDefaultValue: output.autogeneratedDefaultValue
  });
  return { node, inputs: inputPins, result };
}

