let nextGuid = 1;
const guid = () => (nextGuid++).toString(16).toUpperCase().padStart(32, "0");
const nodes = [];

function addNode(className, name, x, y, properties = []) {
  const node = {
    className,
    name,
    x,
    y,
    guid: guid(),
    properties,
    pins: [],
    userDefinedPins: []
  };
  nodes.push(node);
  return node;
}

function addPin(node, name, category, {
  direction = "input",
  container = "None",
  subCategory = "",
  defaultValue,
  autogeneratedDefaultValue,
  hidden = false,
  defaultValueIgnored = false,
  subCategoryObject = "None",
  defaultObject
} = {}) {
  const pin = {
    node,
    id: guid(),
    name,
    category,
    direction,
    container,
    subCategory,
    defaultValue,
    autogeneratedDefaultValue,
    hidden,
    defaultValueIgnored,
    subCategoryObject,
    defaultObject,
    links: []
  };
  node.pins.push(pin);
  return pin;
}

function connect(a, b) {
  a.links.push(b);
  b.links.push(a);
}

function pureMathNode(name, functionName, x, y, returnCategory = "int") {
  const node = addNode(
    "/Script/BlueprintGraph.K2Node_CallFunction",
    name,
    x,
    y,
    [
      "bDefaultsToPureFunc=True",
      `FunctionReference=(MemberParent="/Script/CoreUObject.Class'/Script/Engine.KismetMathLibrary'",MemberName="${functionName}")`
    ]
  );
  addPin(node, "self", "object", {
    hidden: true,
    subCategoryObject: `"/Script/CoreUObject.Class'/Script/Engine.KismetMathLibrary'"`,
    defaultObject: '"/Script/Engine.Default__KismetMathLibrary"'
  });
  const a = addPin(node, "A", "int", { defaultValue: "0", autogeneratedDefaultValue: "0" });
  const b = addPin(node, "B", "int", { defaultValue: "0", autogeneratedDefaultValue: "0" });
  const result = addPin(node, "ReturnValue", returnCategory, {
    direction: "output",
    defaultValue: returnCategory === "bool" ? "false" : "0",
    autogeneratedDefaultValue: returnCategory === "bool" ? "false" : "0"
  });
  return { node, a, b, result };
}

function branchNode(name, x, y) {
  const node = addNode("/Script/BlueprintGraph.K2Node_IfThenElse", name, x, y);
  return {
    node,
    execute: addPin(node, "execute", "exec"),
    then: addPin(node, "then", "exec", { direction: "output" }),
    else: addPin(node, "else", "exec", { direction: "output" }),
    condition: addPin(node, "Condition", "bool", {
      defaultValue: "true",
      autogeneratedDefaultValue: "true"
    })
  };
}

function makeArrayNode(name, x, y, inputCount) {
  const node = addNode(
    "/Script/BlueprintGraph.K2Node_MakeArray",
    name,
    x,
    y,
    [`NumInputs=${inputCount}`]
  );
  const array = addPin(node, "Array", "int", { direction: "output", container: "Array" });
  const inputs = Array.from({ length: inputCount }, (_, index) =>
    addPin(node, `[${index}]`, "int", { defaultValue: "0", autogeneratedDefaultValue: "0" })
  );
  return { node, array, inputs };
}

