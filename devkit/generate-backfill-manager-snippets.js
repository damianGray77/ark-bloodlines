let nextId = 0x5000;
const id = () => (nextId++).toString(16).toUpperCase().padStart(32, "0");

function node(name, className, extra = {}) {
  return { name, className, guid: id(), pins: [], ...extra };
}

function pin(owner, name, type, options = {}) {
  const value = {
    id: id(),
    name,
    type,
    direction: options.direction || "input",
    defaultValue: options.defaultValue,
    autogeneratedDefaultValue: options.autogeneratedDefaultValue,
    defaultObject: options.defaultObject,
    hidden: options.hidden || false,
    reference: options.reference || false,
    const: options.const || false,
    advanced: options.advanced || false,
    links: [],
  };
  owner.pins.push(value);
  return value;
}

function link(a, b) {
  a.links.push({ node: b.owner.name, pin: b.id });
  b.links.push({ node: a.owner.name, pin: a.id });
}

function attachOwners(nodes) {
  for (const n of nodes) for (const p of n.pins) p.owner = n;
}

function q(value) {
  return `"${String(value).replaceAll("\\", "\\\\").replaceAll('"', '\\"')}"`;
}

function renderType(type, p) {
  return [
    `PinType.PinCategory=${q(type.category)}`,
    `PinType.PinSubCategory=${q(type.subCategory || "")}`,
    `PinType.PinSubCategoryObject=${type.object ? q(type.object) : "None"}`,
    "PinType.PinSubCategoryMemberReference=()",
    "PinType.PinValueType=()",
    `PinType.ContainerType=${type.container || "None"}`,
    `PinType.bIsReference=${p.reference ? "True" : "False"}`,
    `PinType.bIsConst=${p.const ? "True" : "False"}`,
    "PinType.bIsWeakPointer=False",
    "PinType.bIsUObjectWrapper=False",
    "PinType.bSerializeAsSinglePrecisionFloat=False",
  ];
}

function renderPin(p) {
  const fields = [
    `PinId=${p.id}`,
    `PinName=${q(p.name)}`,
    ...(p.direction === "output" ? ['Direction="EGPD_Output"'] : []),
    ...renderType(p.type, p),
    ...(p.defaultValue !== undefined ? [`DefaultValue=${q(p.defaultValue)}`] : []),
    ...(p.autogeneratedDefaultValue !== undefined
      ? [`AutogeneratedDefaultValue=${q(p.autogeneratedDefaultValue)}`]
      : []),
    ...(p.defaultObject ? [`DefaultObject=${q(p.defaultObject)}`] : []),
    ...(p.links.length
      ? [`LinkedTo=(${p.links.map(x => `${x.node} ${x.pin},`).join("")})`]
      : []),
    "PersistentGuid=00000000000000000000000000000000",
    `bHidden=${p.hidden ? "True" : "False"}`,
    "bNotConnectable=False",
    "bDefaultValueIsReadOnly=False",
    "bDefaultValueIsIgnored=False",
    `bAdvancedView=${p.advanced ? "True" : "False"}`,
    "bOrphanedPin=False",
  ];
  return `   CustomProperties Pin (${fields.join(",")},)`;
}

function renderNode(n) {
  const lines = [
    `Begin Object Class=/Script/BlueprintGraph.${n.className} Name=${q(n.name)}`,
  ];
  if (n.functionReference) lines.push(`   FunctionReference=${n.functionReference}`);
  if (n.targetType) lines.push(`   TargetType=${q(n.targetType)}`);
  if (n.macroGraphReference) lines.push(`   MacroGraphReference=${n.macroGraphReference}`);
  if (n.resolvedWildcardType) lines.push(`   ResolvedWildcardType=${n.resolvedWildcardType}`);
  if (n.defaultsToPure) lines.push("   bDefaultsToPureFunc=True");
  lines.push(`   NodePosX=${n.x || 0}`, `   NodePosY=${n.y || 0}`, `   NodeGuid=${n.guid}`);
  lines.push(...n.pins.map(renderPin), "End Object");
  return lines.join("\r\n");
}

function writeSnippet(filename, nodes) {
  attachOwners(nodes);
  fs.writeFileSync(path.join(outDir, filename), `${nodes.map(renderNode).join("\r\n")}\r\n`);
}

