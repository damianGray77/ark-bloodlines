function node(className, name, x, y, properties = []) {
  const value = { className, name, x, y, guid: guid(), properties, pins: [], userDefinedPins: [] };
  nodes.push(value);
  return value;
}

function pin(owner, name, category, options = {}) {
  const value = {
    owner,
    id: guid(),
    name,
    category,
    direction: options.direction || "input",
    subCategory: options.subCategory || "",
    subCategoryObject: options.subCategoryObject || "None",
    container: options.container || "None",
    defaultValue: options.defaultValue,
    autogeneratedDefaultValue: options.autogeneratedDefaultValue,
    defaultObject: options.defaultObject,
    hidden: Boolean(options.hidden),
    isReference: Boolean(options.isReference),
    isConst: Boolean(options.isConst),
    defaultValueIgnored: Boolean(options.defaultValueIgnored),
    advanced: Boolean(options.advanced),
    links: []
  };
  owner.pins.push(value);
  return value;
}

function connect(a, b) {
  a.links.push(b);
  b.links.push(a);
}

function reroute(name, category, x, y, options = {}) {
  const n = node("/Script/BlueprintGraph.K2Node_Knot", name, x, y);
  const input = pin(n, "InputPin", category, { ...options, defaultValueIgnored: true });
  const output = pin(n, "OutputPin", category, { ...options, direction: "output" });
  return { node: n, input, output };
}

