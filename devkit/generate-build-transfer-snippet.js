function intMath(name, functionName, x, y, bDefault) {
  const n = pureCall(name, "Engine.KismetMathLibrary", functionName, x, y);
  pin(n, "self", "object", {
    hidden: true,
    subCategoryObject: `"/Script/CoreUObject.Class'/Script/Engine.KismetMathLibrary'"`,
    defaultObject: '"/Script/Engine.Default__KismetMathLibrary"'
  });
  const a = pin(n, "A", "int", { defaultValue: "0", autogeneratedDefaultValue: "0" });
  const b = pin(n, "B", "int", { defaultValue: String(bDefault), autogeneratedDefaultValue: "0" });
  const result = pin(n, "ReturnValue", functionName.startsWith("Greater") ? "bool" : "int", {
    direction: "output",
    defaultValue: functionName.startsWith("Greater") ? "false" : "0",
    autogeneratedDefaultValue: functionName.startsWith("Greater") ? "false" : "0"
  });
  return { node: n, a, b, result };
}

function arrayFunction(name, functionName, elementCategory, elementObject, x, y, includeIndex = false) {
  const n = node(
    "/Script/BlueprintGraph.K2Node_CallArrayFunction",
    name,
    x,
    y,
    [
      "bDefaultsToPureFunc=True",
      `FunctionReference=(MemberParent="/Script/CoreUObject.Class'/Script/Engine.KismetArrayLibrary'",MemberName="${functionName}")`
    ]
  );
  pin(n, "self", "object", {
    hidden: true,
    subCategoryObject: `"/Script/CoreUObject.Class'/Script/Engine.KismetArrayLibrary'"`,
    defaultObject: '"/Script/Engine.Default__KismetArrayLibrary"'
  });
  const target = pin(n, "TargetArray", elementCategory, {
    container: "Array",
    subCategoryObject: elementObject,
    isReference: true,
    isConst: true
  });
  const index = includeIndex
    ? pin(n, "Index", "int", { defaultValue: "0", autogeneratedDefaultValue: "0" })
    : null;
  const result = pin(n, functionName === "Array_Get" ? "Item" : "ReturnValue", functionName === "Array_Get" ? elementCategory : "int", {
    direction: "output",
    subCategoryObject: functionName === "Array_Get" ? elementObject : "None",
    isReference: functionName === "Array_Get",
    defaultValue: functionName === "Array_Get" ? undefined : "0",
    autogeneratedDefaultValue: functionName === "Array_Get" ? undefined : "0"
  });
  return { node: n, target, index, result };
}

