function ancestorBreak(name, x, y) {
  const n = node(
    "/Script/BlueprintGraph.K2Node_BreakStruct",
    name,
    x,
    y,
    [`StructType="/Script/CoreUObject.ScriptStruct'/Script/ShooterGame.DinoAncestorsEntryBlueprint'"`]
  );
  const value = pin(n, "DinoAncestorsEntryBlueprint", "struct", { subCategoryObject: classes.ancestorBP });
  const fields = {};
  for (const [field, category] of [
    ["FemaleName", "string"],
    ["FemaleDinoID1", "int"],
    ["FemaleDinoID2", "int"],
    ["MaleName", "string"],
    ["MaleDinoID1", "int"],
    ["MaleDinoID2", "int"]
  ]) {
    fields[field] = pin(n, field, category, {
      direction: "output",
      defaultValue: category === "int" ? "0" : undefined,
      autogeneratedDefaultValue: category === "int" ? "0" : undefined
    });
  }
  return { node: n, value, fields };
}

