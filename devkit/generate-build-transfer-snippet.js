function renderPin(value) {
  const parts = [
    `PinId=${value.id}`,
    `PinName="${value.name}"`,
    ...(value.direction === "output" ? ['Direction="EGPD_Output"'] : []),
    `PinType.PinCategory="${value.category}"`,
    `PinType.PinSubCategory="${value.subCategory}"`,
    `PinType.PinSubCategoryObject=${value.subCategoryObject}`,
    "PinType.PinSubCategoryMemberReference=()",
    "PinType.PinValueType=()",
    `PinType.ContainerType=${value.container}`,
    `PinType.bIsReference=${value.isReference ? "True" : "False"}`,
    `PinType.bIsConst=${value.isConst ? "True" : "False"}`,
    "PinType.bIsWeakPointer=False",
    "PinType.bIsUObjectWrapper=False",
    "PinType.bSerializeAsSinglePrecisionFloat=False",
    ...(value.defaultValue !== undefined ? [`DefaultValue="${value.defaultValue}"`] : []),
    ...(value.autogeneratedDefaultValue !== undefined ? [`AutogeneratedDefaultValue="${value.autogeneratedDefaultValue}"`] : []),
    ...(value.defaultObject !== undefined ? [`DefaultObject=${value.defaultObject}`] : []),
    ...(value.links.length
      ? [`LinkedTo=(${value.links.map(link => `${link.owner.name} ${link.id},`).join("")})`]
      : []),
    "PersistentGuid=00000000000000000000000000000000",
    `bHidden=${value.hidden ? "True" : "False"}`,
    "bNotConnectable=False",
    "bDefaultValueIsReadOnly=False",
    `bDefaultValueIsIgnored=${value.defaultValueIgnored ? "True" : "False"}`,
    `bAdvancedView=${value.advanced ? "True" : "False"}`,
    "bOrphanedPin=False"
  ];
  return `   CustomProperties Pin (${parts.join(",")},)`;
}

function renderNode(value) {
  return [
    `Begin Object Class=${value.className} Name="${value.name}"`,
    ...value.properties.map(property => `   ${property}`),
    `   NodePosX=${value.x}`,
    `   NodePosY=${value.y}`,
    `   NodeGuid=${value.guid}`,
    ...value.pins.map(renderPin),
    ...value.userDefinedPins.map(item => `   ${item}`),
    "End Object"
  ].join("\n");
}

